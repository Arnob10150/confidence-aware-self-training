from __future__ import annotations

"""Regenerates figures/imbalance_fix_combined.pdf from the real class-aware
iteration logs (class_aware_crest_iteration_logs.csv, 5% labels, 5-seed
average), replacing the pre-existing figure in the paper's figures/ folder
that was generated by lost original code and no longer matched the
regenerated Table II / Sec. IV-C numbers exactly.

Matches the visual style of 10_combine_figures.py.
"""

import matplotlib

matplotlib.use("Agg")
matplotlib.rcParams["pdf.fonttype"] = 42  # Type 42 (TrueType), not Type 3, for IEEE PDF eXpress

import matplotlib.pyplot as plt
import pandas as pd

from utils import FIGURES_DIR

PRIMARY = "framingham"
TRUE_POSITIVE_RATE = 0.152


def _curve(ax, x, mean, color, label, linestyle, marker):
    ax.plot(x, mean, color=color, linestyle=linestyle, marker=marker, markersize=4.5, linewidth=1.8, label=label)


def combine_imbalance_fix_panels():
    imb = pd.read_csv("results/imbalance_analysis.csv")
    imb = imb[imb["config"] == PRIMARY]
    ca = pd.read_csv("results/class_aware_crest_iteration_logs.csv")
    ca5 = ca[(ca["method"] == "ClassAwareST") & (ca["ratio"] == 0.05)]

    styles = {
        "vanilla": ("#D85A30", "--", "^", "Standard"),
        "dynamic": ("#7A4EB3", "-.", "D", "Dynamic"),
    }

    fig, axes = plt.subplots(2, 1, figsize=(3.6, 4.8))

    # (a) Pseudo-label positive rate by iteration
    ax = axes[0]
    for variant, (color, ls, marker, label) in styles.items():
        grouped = imb[imb["variant"] == variant].groupby("iter")["pl_pos_rate"].mean()
        if grouped.empty:
            continue
        _curve(ax, grouped.index.to_numpy(), grouped.to_numpy(), color, label, ls, marker)
    ca_grouped = ca5.groupby("iter")["pl_pos_rate"].mean()
    _curve(ax, ca_grouped.index.to_numpy(), ca_grouped.to_numpy(), "#1D9E75", "Class-Aware (proposed)", "-", "o")
    ax.axhline(TRUE_POSITIVE_RATE, color="gray", linestyle=":", linewidth=1.2, label="True positive rate")
    ax.set_xlabel("Self-training iteration", fontsize=11)
    ax.set_ylabel("Pseudo-label positive rate", fontsize=11)
    ax.set_title("(a) Positive rate by iteration", fontsize=11)
    ax.tick_params(labelsize=10)
    ax.margins(y=0.1)
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.34), ncol=2, fontsize=9, frameon=False, columnspacing=1.0, handletextpad=0.4)
    ax.grid(alpha=0.12)

    # (b) Cumulative positive rate by iteration
    ax = axes[1]
    for variant, (color, ls, marker, label) in styles.items():
        grouped = imb[imb["variant"] == variant].groupby("iter")["cumulative_pos_rate"].mean()
        if grouped.empty:
            continue
        _curve(ax, grouped.index.to_numpy(), grouped.to_numpy(), color, label, ls, marker)
    ca_cum = ca5.groupby("iter")["cumulative_pos_rate"].mean()
    _curve(ax, ca_cum.index.to_numpy(), ca_cum.to_numpy(), "#1D9E75", "Class-Aware (proposed)", "-", "o")
    ax.set_xlabel("Self-training iteration", fontsize=11)
    ax.set_ylabel("Cumulative positive rate", fontsize=11)
    ax.set_title("(b) Cumulative positive rate", fontsize=11)
    ax.tick_params(labelsize=10)
    ax.margins(y=0.1)
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.34), ncol=2, fontsize=9, frameon=False, columnspacing=1.0, handletextpad=0.4)
    ax.grid(alpha=0.12)

    fig.subplots_adjust(hspace=0.95)
    plt.savefig(FIGURES_DIR / "imbalance_fix_combined.pdf", bbox_inches="tight", pad_inches=0.08)
    plt.close()
    print("Saved results/figures/imbalance_fix_combined.pdf")


if __name__ == "__main__":
    combine_imbalance_fix_panels()
