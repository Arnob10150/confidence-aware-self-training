from __future__ import annotations

import importlib
from pathlib import Path


STEPS = [
    ("1_preprocessing", "preprocess"),
    ("2_baseline_supervised", "run_baselines"),
    ("3_self_training_variants", "run_self_training"),
    ("4_ssl_comparison", "run_ssl_comparison"),
    ("5_error_propagation", "run_error_propagation"),
    ("6_shap_analysis", "run_shap"),
    ("7_imbalance_analysis", "run_imbalance_analysis"),
    ("8_visualizations", "run_visualizations"),
]


def write_results_readme() -> None:
    text = """# Results README

Generated by `python run_all.py`.

## Tables
- `results/dataset_summary.csv`: Framingham dimensions, feature counts, missing rows, and TenYearCHD class balance.
- `results/missing_before.csv`: missing-value counts before median imputation.
- `results/baseline_results.csv`: supervised-only LR/SVM/RF/XGB metrics for every labeled ratio, seed, and dataset configuration.
- `results/cv_ceiling.csv`: full-label 5-fold cross-validation ceiling for LR/SVM/RF/XGB.
- `results/selftraining_results.csv`: vanilla, static-high, and dynamic self-training metrics for every classifier, labeled ratio, seed, and dataset configuration.
- `results/selftraining_iteration_logs.csv`: iteration-level pseudo-label logs for all self-training runs.
- `results/ssl_comparison.csv`: dynamic XGB self-training, Mean Teacher-style self-distillation, and Label Propagation metrics.
- `results/error_propagation.csv`: focused 5% labeled XGB pseudo-label quality logs for the three threshold schedules.
- `results/imbalance_analysis.csv`: focused 5% labeled XGB pseudo-label class-balance logs for the three threshold schedules.
- `results/shap_importance.csv`: mean absolute SHAP values at 5% and 40% labeled regimes.
- `results/summary_table.csv`: mean and standard deviation aggregation for paper tables.

## Figures
- `results/figures/accuracy_vs_labeled_ratio.png`: supervised vs dynamic self-training accuracy.
- `results/figures/f1_vs_labeled_ratio.png`: XGB supervised and self-training F1 by labeled ratio.
- `results/figures/recall_vs_labeled_ratio.png`: XGB supervised and self-training recall by labeled ratio.
- `results/figures/auc_vs_labeled_ratio.png`: supervised vs dynamic self-training AUC.
- `results/figures/threshold_variant_auc.png`: XGB threshold strategy comparison.
- `results/figures/ssl_method_auc.png`: dynamic self-training vs Mean Teacher vs Label Propagation.
- `results/figures/error_propagation_pl_acc.png`: pseudo-label accuracy by iteration.
- `results/figures/pseudo_label_positive_rate.png`: per-iteration pseudo-label positive-rate collapse/expansion.
- `results/figures/cumulative_pseudo_label_positive_rate.png`: cumulative pseudo-label positive rate by iteration.
- `results/figures/noise_injection_cumulative_wrong.png`: cumulative wrong pseudo-labels by iteration.
- `results/figures/cumulative_error_rate.png`: cumulative pseudo-label error rate.
- `results/figures/roc_dynamic_xgb_by_ratio.png`: ROC curves for dynamic XGB.
- `results/figures/target_distribution.png`: HIGH vs non-HIGH class balance.
- `results/figures/workflow_diagram.png`: end-to-end experimental workflow.
- `results/shap/*.png`: SHAP summary, bar, and HIGH-risk waterfall plots.

## Paper Mapping
- Paper Section 3 uses Framingham preprocessing, stratified splitting, imbalance-aware classifiers, threshold variants, SSL comparison, error propagation, pseudo-label class-balance analysis, and SHAP methods.
- Paper Sections 4.1-4.4 use `baseline_results.csv`, `selftraining_results.csv`, and `summary_table.csv`.
- Paper Section 4.5 uses `threshold_variant_auc.png` and the XGB dynamic/static/vanilla rows.
- Paper Section 4.6 uses `ssl_comparison.csv` and `ssl_method_auc.png`.
- Paper Section 4.7 uses `error_propagation.csv` and the error/noise figures.
- Paper Section 4.8 uses `imbalance_analysis.csv` and the pseudo-label positive-rate figures.
- Paper Section 4.9 uses `shap_importance.csv` and the SHAP figures.
"""
    Path("results_README.md").write_text(text, encoding="utf-8")


def main() -> None:
    for module_name, function_name in STEPS:
        print(f"\n=== Running {module_name}.{function_name} ===")
        module = importlib.import_module(module_name)
        getattr(module, function_name)()
    write_results_readme()
    print("\nAll experiment outputs generated.")


if __name__ == "__main__":
    main()
